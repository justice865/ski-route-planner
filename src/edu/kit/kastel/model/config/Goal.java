package edu.kit.kastel.model.config;

/**
 * The Goal enum represents the different goals that a skier can have.
 * @author uqibg
 */
public enum Goal {
    /**
     * represents the goal of maximizing altitude.
     */
    ALTITUDE,
    /**
     * represents the goal of maximizing distance.
     */
    DISTANCE,
    /**
     * represents the goal of maximizing the number of slopes.
     */
    NUMBER,
    /**
     * represents the goal of maximizing the number of unique slopes.
     */
    UNIQUE
}

