package edu.kit.kastel.model.graph.types;

/**
 * The Surface enum represents the different types of surfaces that a slope can have.
 * @author uqibg
 */
public enum Surface {
    /**
     * represents a regular surface.
     */
    REGULAR,
    /**
     * represents a bumpy surface.
     */
    BUMPY,
    /**
     * represents an icy surface.
     */
    ICY
}

