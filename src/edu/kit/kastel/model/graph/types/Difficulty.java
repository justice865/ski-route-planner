package edu.kit.kastel.model.graph.types;

/**
 * The Difficulty enum represents the difficulty levels of ski slopes.
 * @author uqibg
 */
public enum Difficulty {
    /**
     * Easy difficulty level, represented by a blue slope.
     */
    BLUE,
    /**
     * Medium difficulty level, represented by a red slope.
     */
    RED,
    /**
     * Hard difficulty level, represented by a black slope.
     */
    BLACK
}

